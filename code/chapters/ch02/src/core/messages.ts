/**
 * Message role definitions and immutable factory functions.
 * Four roles (system/user/assistant/tool) map to the Chat Completions API protocol.
 * validateToolPairing checks whether all tool_call_id values are paired before sending requests,
 * Prevent orphan results or missing items from entering the next turn. Factory functions freeze message objects to maintain immutability.
 */
export type Role = "system" | "user" | "assistant" | "tool";

// The message contract prevents orphaned tool results or unfilled model tool calls from entering the next turn.
export class MessageContractError extends Error {
  override readonly name = "MessageContractError";
}

export interface ToolCall {
  // Unique call ID generated by vendor, used by tool result for backfill correlation.
  readonly id: string;
  // Tool name used for registry lookups.
  readonly name: string;
  // Raw JSON argument text, parsed only by ToolRegistry.
  readonly arguments: string;
}

export interface SystemMessage {
  // Discriminator tag; system constraints temporarily prepended before each turn request.
  readonly role: "system";
  // System prompt body.
  readonly content: string;
}

export interface UserMessage {
  // Discriminator tag; the starting point of a run.
  readonly role: "user";
  // Original user task text.
  readonly content: string;
}

export interface AssistantMessage {
  // Discriminator tag; model reply.
  readonly role: "assistant";
  // Final text, or null during tool calls.
  readonly content: string | null;
  // Tool calls proposed in this reply that must be backfilled item by item.
  readonly toolCalls: readonly ToolCall[];
}

export interface ToolMessage {
  // Discriminator tag; backfill message after tool execution.
  readonly role: "tool";
  // Successful output or failure body with error codes.
  readonly content: string;
  // Unique ID corresponding to assistant calls.
  readonly toolCallId: string;
}

// Discriminated union of four message kinds, used for exhaustive branching in history validation and SDK conversion.
export type ChatMessage = SystemMessage | UserMessage | AssistantMessage | ToolMessage;

// Centrally validates all message fields; allowEmpty is used only for roles whose protocol permits empty bodies.
function requireString(value: unknown, field: string, allowEmpty = false): string {
  if (typeof value !== "string") {
    throw new MessageContractError(`${field} must be a string`);
  }
  if (!allowEmpty && value.length === 0) {
    throw new MessageContractError(`${field} must not be empty`);
  }
  return value;
}

// Creates and freezes tool call; parameters parse and validate only during registry prepare stage.
export function toolCall(id: unknown, name: unknown, argumentsJson: unknown): ToolCall {
  return Object.freeze({
    id: requireString(id, "tool call id"),
    name: requireString(name, "tool call name"),
    arguments: requireString(argumentsJson, "tool call arguments", true),
  });
}

// Factory functions freeze messages to ensure model request history is not modified externally after creation.
export function systemMessage(content: string): SystemMessage {
  return Object.freeze({ role: "system", content: requireString(content, "system content", true) });
}

// Create a user message; the message layer allows empty text and does not change higher-level input policy.
export function userMessage(content: string): UserMessage {
  return Object.freeze({ role: "user", content: requireString(content, "user content", true) });
}

// Create a model message and ensure tool call IDs pair without ambiguity in a single reply.
export function assistantMessage(
  content: string | null,
  toolCalls: readonly ToolCall[] = [],
): AssistantMessage {
  if (content !== null) {
    requireString(content, "assistant content", true);
  }
  // The same assistant message must not declare duplicate tool_call_id, or results cannot backfill without ambiguity.
  const ids = toolCalls.map((call) => call.id);
  if (new Set(ids).size !== ids.length) {
    throw new MessageContractError("assistant tool call ids must be unique");
  }
  return Object.freeze({ role: "assistant", content, toolCalls: Object.freeze([...toolCalls]) });
}

// Creates tool result message, requiring non-empty correlation ID to keep calls auditable.
export function toolMessage(content: string, toolCallId: string): ToolMessage {
  return Object.freeze({
    role: "tool",
    content: requireString(content, "tool content", true),
    toolCallId: requireString(toolCallId, "tool_call_id"),
  });
}

// Validates call and result pairing invariants across full history, preventing corrupted state from leaking before requesting provider.
export function validateToolPairing(messages: readonly ChatMessage[]): void {
  // pending retains call IDs of the current assistant message that have not yet received results.
  const pending = new Set<string>();

  for (const message of messages) {
    if (pending.size > 0) {
      if (message.role !== "tool") {
        throw new MessageContractError(
          `missing tool results for ids: ${JSON.stringify([...pending].sort())}`,
        );
      }
      if (!pending.delete(message.toolCallId)) {
        throw new MessageContractError(`unexpected tool result id: ${message.toolCallId}`);
      }
      continue;
    }

    if (message.role === "tool") {
      throw new MessageContractError(`orphan tool result id: ${message.toolCallId}`);
    }
    if (message.role === "assistant" && message.toolCalls.length > 0) {
      for (const call of message.toolCalls) {
        pending.add(call.id);
      }
    }
  }

  if (pending.size > 0) {
    throw new MessageContractError(
      `missing tool results for ids: ${JSON.stringify([...pending].sort())}`,
    );
  }
}
